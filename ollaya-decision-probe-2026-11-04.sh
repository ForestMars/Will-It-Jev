#!/usr/bin/env bash
#
# ollaya-decision-probe.sh
#
# Send an actual typed decision request to Ollaya's native POST /api/decide API.
# Unlike the readiness probe, this defaults to a realistic support-ticket
# classification and reports the model's answers and probabilities.
#
# Requirements: bash, curl, jq
#
# Usage:
#   ./ollaya-decision-probe.sh
#   ./ollaya-decision-probe.sh "I cannot log in after resetting my password."
#   ./ollaya-decision-probe.sh - < ticket.txt
#
# Configuration:
#   OLLAYA_URL                    default: http://127.0.0.1:11435
#   OLLAYA_MODEL                  default: laya:multilingual
#   OLLAYA_KEEP_ALIVE             default: 5m
#   OLLAYA_API_KEY                optional Bearer token
#   OLLAYA_REQUEST_ID             optional request ID (generated by default)
#   OLLAYA_EXPECTED_DEPARTMENT    optional expected label: billing|technical|account|other
#   OLLAYA_EXPECTED_REFUND        optional expected boolean: true|false
#   OLLAYA_CONNECT_TIMEOUT_SECONDS default: 3
#   OLLAYA_INFERENCE_TIMEOUT_SECONDS default: 120
#
# With no state supplied, the built-in duplicate-charge fixture is used and
# checked against the expected outcome (billing + refund requested). For a
# caller-supplied state, semantic expectations are only checked when the two
# OLLAYA_EXPECTED_* variables are explicitly set.

set -Eeuo pipefail

OLLAYA_URL="${OLLAYA_URL:-http://127.0.0.1:11435}"
OLLAYA_URL="${OLLAYA_URL%/}"
OLLAYA_MODEL="${OLLAYA_MODEL:-laya:multilingual}"
OLLAYA_KEEP_ALIVE="${OLLAYA_KEEP_ALIVE:-5m}"
CONNECT_TIMEOUT_SECONDS="${OLLAYA_CONNECT_TIMEOUT_SECONDS:-3}"
INFERENCE_TIMEOUT_SECONDS="${OLLAYA_INFERENCE_TIMEOUT_SECONDS:-120}"
REQUEST_ID="${OLLAYA_REQUEST_ID:-ollaya-decision-$(date +%s)}"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

fail() { printf '[FAIL] %s\n' "$*" >&2; exit 1; }
pass() { printf '[PASS] %s\n' "$*"; }
info() { printf '[INFO] %s\n' "$*"; }
section() {
    printf '\n================================================================\n  %s\n================================================================\n' "$1"
}
usage() {
    cat <<'USAGE'
Usage:
  ollaya-decision-probe.sh [STATE]
  printf '%s' 'STATE' | ollaya-decision-probe.sh -

With no STATE argument, the script submits a built-in duplicate-charge
support ticket and checks for a billing classification plus a refund request.

Environment variables:
  OLLAYA_URL, OLLAYA_MODEL, OLLAYA_KEEP_ALIVE, OLLAYA_API_KEY
  OLLAYA_REQUEST_ID, OLLAYA_EXPECTED_DEPARTMENT, OLLAYA_EXPECTED_REFUND
  OLLAYA_CONNECT_TIMEOUT_SECONDS, OLLAYA_INFERENCE_TIMEOUT_SECONDS
USAGE
}

for cmd in curl jq; do
    command -v "$cmd" >/dev/null 2>&1 || fail "Required command not found: $cmd"
done

if [[ "$REQUEST_ID" == *[!A-Za-z0-9._-]* ]] || [[ ${#REQUEST_ID} -lt 1 || ${#REQUEST_ID} -gt 128 ]]; then
    fail 'OLLAYA_REQUEST_ID must be 1–128 characters from A-Z, a-z, 0-9, dot, underscore or hyphen'
fi

# Resolve state input. Use '-' explicitly for stdin so a non-interactive
# invocation with no piped input cannot block waiting for EOF.
USING_DEFAULT_FIXTURE=false
if [[ $# -gt 1 ]]; then
    usage >&2
    exit 2
elif [[ $# -eq 1 && "$1" == '-' ]]; then
    STATE="$(cat)"
elif [[ $# -eq 1 ]]; then
    STATE="$1"
elif [[ -n "${OLLAYA_STATE:-}" ]]; then
    STATE="$OLLAYA_STATE"
else
    STATE='I was charged twice for my subscription this month. Please refund the duplicate charge.'
    USING_DEFAULT_FIXTURE=true
fi

[[ -n "$STATE" ]] || fail 'The decision state is empty; pass it as an argument, OLLAYA_STATE, or stdin'

EXPECTED_DEPARTMENT="${OLLAYA_EXPECTED_DEPARTMENT:-}"
EXPECTED_REFUND="${OLLAYA_EXPECTED_REFUND:-}"
if [[ "$USING_DEFAULT_FIXTURE" == true ]]; then
    EXPECTED_DEPARTMENT="${EXPECTED_DEPARTMENT:-billing}"
    EXPECTED_REFUND="${EXPECTED_REFUND:-true}"
fi

case "$EXPECTED_DEPARTMENT" in
    ''|billing|technical|account|other) ;;
    *) fail 'OLLAYA_EXPECTED_DEPARTMENT must be billing, technical, account, or other' ;;
esac
case "$EXPECTED_REFUND" in
    ''|true|false) ;;
    *) fail 'OLLAYA_EXPECTED_REFUND must be true or false' ;;
esac

curl_with_auth() {
    if [[ -n "${OLLAYA_API_KEY:-}" ]]; then
        curl -sS "$@" --header "Authorization: Bearer ${OLLAYA_API_KEY}"
    else
        curl -sS "$@"
    fi
}

show_api_error() {
    local body_file="$1"
    if jq -e . "$body_file" >/dev/null 2>&1; then
        jq -r '"code: \(.code // "unknown")", "error: \(.error // .message // "no error message")"' "$body_file" >&2
        jq -c '.detail // empty' "$body_file" >&2 || true
    else
        head -c 2000 "$body_file" >&2 || true
        printf '\n' >&2
    fi
}

section 'DECISION REQUEST'
info "Endpoint: ${OLLAYA_URL}/api/decide"
info "Requested model: ${OLLAYA_MODEL}"
info "Request ID: ${REQUEST_ID}"
if [[ "$USING_DEFAULT_FIXTURE" == true ]]; then
    info 'Input: built-in duplicate-charge support ticket'
else
    info 'Input: caller-supplied state'
fi
printf '\nState sent to the model:\n%s\n' "$STATE"

# Two separate typed questions are evaluated over the same state in one
# decision request: a four-way department choice and a binary refund question.
REQUEST_BODY="$(jq -cn \
    --arg model "$OLLAYA_MODEL" \
    --arg state "$STATE" \
    --arg keep_alive "$OLLAYA_KEEP_ALIVE" \
    '{
      model: $model,
      state: $state,
      questions: {
        department: {
          type: "choice",
          instructions: "Which support department should own this customer request?",
          criteria: {
            billing: "Charges, payments, invoices, subscriptions, duplicate charges, and refunds.",
            technical: "Product defects, errors, outages, integrations, and other technical failures.",
            account: "Login, authentication, account access, profile changes, and account administration.",
            other: "A request that does not fit billing, technical, or account support."
          }
        },
        refund: {
          type: "noul",
          instructions: "Is the customer explicitly asking to receive money back for a charge?",
          criteria: {
            "true": "The customer explicitly requests a refund or money back.",
            "false": "The customer does not request a refund or money back."
          }
        }
      },
      keep_alive: $keep_alive
    }')"

printf '\nExact JSON request body:\n'
printf '%s\n' "$REQUEST_BODY" | jq .

RESPONSE_BODY="${TMP_DIR}/decision-response.json"
HTTP_STATUS="$(curl_with_auth \
    --connect-timeout "$CONNECT_TIMEOUT_SECONDS" \
    --max-time "$INFERENCE_TIMEOUT_SECONDS" \
    --header 'Content-Type: application/json' \
    --header "X-Request-Id: ${REQUEST_ID}" \
    --data-binary "$REQUEST_BODY" \
    --output "$RESPONSE_BODY" \
    --write-out '%{http_code}' \
    "${OLLAYA_URL}/api/decide")" \
    || fail "POST /api/decide could not complete (connection failure or timeout after ${INFERENCE_TIMEOUT_SECONDS}s)"

if [[ "$HTTP_STATUS" != '200' ]]; then
    printf '[FAIL] POST /api/decide returned HTTP %s\n' "$HTTP_STATUS" >&2
    show_api_error "$RESPONSE_BODY"
    exit 1
fi

# Validate that Ollaya performed inference and returned both requested
# answer types. A 200 response alone is insufficient (it could be a load call).
jq -e '
    .done_reason == "decide" and
    .state_truncated == false and
    (.model | type == "string" and length > 0) and
    (.answers.department.type == "choice") and
    (.answers.department.choice == "billing" or
     .answers.department.choice == "technical" or
     .answers.department.choice == "account" or
     .answers.department.choice == "other") and
    (.answers.department.confidence | type == "number" and . >= 0 and . <= 1) and
    (.answers.department.probabilities | type == "object") and
    (.answers.refund.type == "noul") and
    (.answers.refund.noul | type == "number" and . >= 0 and . <= 1) and
    (.usage.input_tokens | type == "number" and . > 0) and
    (.usage.output_tokens | type == "number" and . == 0)
' "$RESPONSE_BODY" >/dev/null 2>&1 || {
    printf '[FAIL] HTTP 200, but Ollaya did not return the expected completed decision response:\n' >&2
    jq . "$RESPONSE_BODY" >&2 2>/dev/null || cat "$RESPONSE_BODY" >&2
    exit 1
}

ANSWERED_MODEL="$(jq -r '.model' "$RESPONSE_BODY")"
DEPARTMENT="$(jq -r '.answers.department.choice' "$RESPONSE_BODY")"
DEPARTMENT_CONFIDENCE="$(jq -r '.answers.department.confidence' "$RESPONSE_BODY")"
REFUND_PROBABILITY="$(jq -r '.answers.refund.noul' "$RESPONSE_BODY")"
INPUT_TOKENS="$(jq -r '.usage.input_tokens' "$RESPONSE_BODY")"
TOTAL_DURATION_NS="$(jq -r '.total_duration // 0' "$RESPONSE_BODY")"
LOAD_DURATION_NS="$(jq -r '.load_duration // 0' "$RESPONSE_BODY")"
EVAL_DURATION_NS="$(jq -r '.eval_duration // 0' "$RESPONSE_BODY")"
RESPONSE_REQUEST_ID="${REQUEST_ID}"

section 'MODEL DECISION'
pass 'Ollaya completed a real typed decision (done_reason=decide)'
info "Answering model: ${ANSWERED_MODEL}"
printf 'Department: %s (confidence %s)\n' "$DEPARTMENT" "$DEPARTMENT_CONFIDENCE"
printf 'Department probabilities:\n'
jq -r '.answers.department.probabilities | to_entries[] | "  \(.key): \((.value * 10000 | round) / 100)%"' "$RESPONSE_BODY"
printf 'Refund requested: %s%% probability\n' "$(jq -r '((.answers.refund.noul * 10000 | round) / 100)' "$RESPONSE_BODY")"
info "Input tokens: ${INPUT_TOKENS} (output tokens: 0; decision models do not generate text)"
info "Total duration: $((TOTAL_DURATION_NS / 1000000)) ms"
info "Load duration:  $((LOAD_DURATION_NS / 1000000)) ms"
info "Eval duration:  $((EVAL_DURATION_NS / 1000000)) ms"

# Optional semantic assertions. The built-in fixture enables both by default;
# custom state only gets these checks when the caller asks for them.
if [[ -n "$EXPECTED_DEPARTMENT" ]]; then
    if [[ "$DEPARTMENT" == "$EXPECTED_DEPARTMENT" ]]; then
        pass "Department matches expected label: ${EXPECTED_DEPARTMENT}"
    else
        fail "Decision mismatch: expected department '${EXPECTED_DEPARTMENT}', model chose '${DEPARTMENT}'"
    fi
fi

if [[ -n "$EXPECTED_REFUND" ]]; then
    REFUND_IS_TRUE=false
    if jq -e '.answers.refund.noul >= 0.5' "$RESPONSE_BODY" >/dev/null; then
        REFUND_IS_TRUE=true
    fi
    if [[ "$EXPECTED_REFUND" == "$REFUND_IS_TRUE" ]]; then
        pass "Refund decision matches expected value: ${EXPECTED_REFUND}"
    else
        fail "Decision mismatch: expected refund='${EXPECTED_REFUND}', model probability was ${REFUND_PROBABILITY}"
    fi
fi

section 'RESULT'
pass 'Ollaya accepted the state, evaluated both typed questions, and returned structured answers'
